"""Eval runs for the UI.

The eval harness is two CLI programs that already work from a terminal:
``run_eval.py`` drives synthetic callers through a scripted conversation, and
``score_eval.py`` reads the trace database afterwards and judges it. Neither has
an HTTP surface, and neither should — they publish to LiveKit and read the
worker's own database, which is exactly the kind of thing that belongs behind a
server-side process boundary.

This module wraps them so the browser can start a run and watch it, without the
browser ever seeing a subprocess handle or a database path.

Two things here are deliberate and easy to get wrong:

  - A run takes minutes (seven cases, ~8s of audio each, plus scoring), so it is
    run in a background thread and the endpoint returns immediately with a job
    id. Making the HTTP request block would mean a browser-side timeout
    indistinguishable from a hung agent.

  - Only one run at a time. Two concurrent runs would join the *same* room with
    *different* identities, and the scorer's manifest would attribute one
    caller's math case to the other caller. The scorer can already handle that
    when it is told (``--users 2``), but it cannot handle it when it is not, and
    a second run must not look like the first.
"""

import json
import os
import subprocess
import sys
import threading
import time
import uuid

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RUN_DIR = os.path.join(ROOT, ".run")
LAST_REPORT = os.path.join(RUN_DIR, "last_report.json")

RUN_EVAL = os.path.join(ROOT, "run_eval.py")
SCORE_EVAL = os.path.join(ROOT, "score_eval.py")

# The eval audio is generated by generate_test_audio.py and has to exist before a
# run; a missing file otherwise fails deep inside the LiveKit publish with a
# wave-format error that says nothing about the cause.
AUDIO_DIR = os.path.join(ROOT, "test_audio")

_lock = threading.Lock()
_job: dict | None = None


def _now() -> float:
    return time.time()


def current_job() -> dict | None:
    """The running or most recent job. A copy, so a caller mutating it cannot
    corrupt the shared state that `start` will hand to the next request."""
    with _lock:
        return dict(_job) if _job else None


def last_report() -> dict | None:
    if not os.path.exists(LAST_REPORT):
        return None
    try:
        with open(LAST_REPORT, encoding="utf-8") as handle:
            return json.load(handle)
    except (OSError, json.JSONDecodeError):
        # A truncated report is worse than no report: it would render as a
        # partial score, and a partial score reads as a real one.
        return None


def preflight() -> list[str]:
    """What is missing before a run can start, phrased as fixes.

    Checked up front so the UI can disable the run button and say why, rather
    than letting the run fail ninety seconds in.
    """
    problems = []
    if not os.path.exists(RUN_EVAL):
        problems.append("run_eval.py is missing.")
    if not os.path.exists(SCORE_EVAL):
        problems.append("score_eval.py is missing.")
    if not os.path.isdir(AUDIO_DIR) or not os.listdir(AUDIO_DIR):
        problems.append(
            "No test audio found. Generate it with: python3 generate_test_audio.py"
        )
    return problems


def start(users: int = 1, rotate: int = 0, cases: str | None = None) -> dict:
    """Start a run, or return the job already in flight.

    Returns a job dict rather than raising for "already running", because that is
    a normal answer to a normal double-click, not an error.
    """
    global _job

    # The check and the assignment happen in one critical section so two
    # simultaneous POSTs cannot both see "no job" and both start a run. And the
    # assignment is inline rather than via _set_job(): threading.Lock is not
    # reentrant, so calling the setter from inside this `with` deadlocks — and
    # because the lock is held by the request thread, the endpoint hangs until
    # the client gives up rather than returning an error.
    with _lock:
        if _job is not None and _job.get("state") == "running":
            return dict(_job)

        job = {
            "id": uuid.uuid4().hex[:12],
            "state": "running",
            "started_at": _now(),
            "finished_at": None,
            "users": users,
            "rotate": rotate,
            "cases": cases,
            "stage": "starting",
            "log": [],
            "error": None,
            "report": None,
        }
        _job = job

    thread = threading.Thread(target=_run, args=(job,), daemon=True)
    thread.start()
    return dict(job)


def _append(job_id: str, line: str) -> None:
    with _lock:
        if _job and _job["id"] == job_id:
            _job["log"].append(line.rstrip())
            # Unbounded log growth on a long-running API process is a slow leak.
            # 200 lines is more than enough to diagnose a failed run.
            _job["log"] = _job["log"][-200:]


def _set_stage(job_id: str, stage: str) -> None:
    with _lock:
        if _job and _job["id"] == job_id:
            _job["stage"] = stage


def _run(job: dict) -> None:
    """Drive run_eval.py then score_eval.py, streaming their output into the job.

    Not streamed to the client incrementally — the UI polls — but captured
    either way, because the tail of a failed run is the only useful thing about
    it.
    """
    job_id = job["id"]
    try:
        os.makedirs(RUN_DIR, exist_ok=True)

        cmd = [sys.executable, RUN_EVAL, "--users", str(job["users"])]
        if job["rotate"]:
            cmd += ["--rotate", str(job["rotate"])]
        if job["cases"]:
            cmd += ["--cases", job["cases"]]

        _set_stage(job_id, "running calls")
        result = _spawn(cmd, job_id)

        if result.returncode != 0:
            _finish(job_id, state="failed",
                    error=f"run_eval.py exited {result.returncode}. See the log for the last output.")
            return

        # Scoring reads the trace database the run just wrote. If the run wrote
        # nothing, score_eval still produces a report — a zero-case one — and
        # that is reported as a failure here rather than as "0/0 passed", which
        # would look like success.
        _set_stage(job_id, "scoring")
        score = _spawn([sys.executable, SCORE_EVAL, "--json"], job_id)

        if score.returncode != 0:
            _finish(job_id, state="failed",
                    error=f"score_eval.py exited {score.returncode}. See the log.")
            return

        report = _parse_report(score.stdout, job_id)
        if report is None:
            _finish(job_id, state="failed",
                    error="Could not read the scorer's JSON report. See the log.")
            return

        if report.get("total", 0) == 0:
            _finish(job_id, state="failed", report=report,
                    error="The run produced no scorable calls. Check that the worker "
                          "was running and in the same room.")
            return

        with open(LAST_REPORT, "w", encoding="utf-8") as handle:
            json.dump(report, handle, indent=2)

        _finish(job_id, state="done", report=report)

    except Exception as exc:  # noqa: BLE001
        _finish(job_id, state="failed", error=f"{type(exc).__name__}: {exc}")


def _spawn(cmd: list[str], job_id: str) -> subprocess.CompletedProcess:
    """Run a CLI tool, capturing stdout and stderr together.

    stderr is merged into stdout because these tools print progress to both and
    a log that interleaves them in real order is the one you can debug from.
    """
    process = subprocess.Popen(
        cmd,
        cwd=ROOT,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        bufsize=1,
    )
    lines = []
    assert process.stdout is not None
    for line in process.stdout:
        lines.append(line)
        _append(job_id, line)
    process.wait()
    return subprocess.CompletedProcess(cmd, process.returncode, "".join(lines), "")


def _parse_report(stdout: str, job_id: str) -> dict | None:
    """Pull the report out of the scorer's stdout.

    The scorer prints a human report and then the JSON, so the JSON is the last
    top-level object in the stream. Scanning backwards for a brace that parses is
    more robust than assuming it is the final line — a stray progress print
    after it would otherwise swallow the whole report.
    """
    text = stdout.strip()
    for start in range(len(text) - 1, -1, -1):
        if text[start] != "{":
            continue
        try:
            parsed = json.loads(text[start:])
        except json.JSONDecodeError:
            continue
        if isinstance(parsed, dict) and "total" in parsed:
            return parsed
    _append(job_id, "Could not find a JSON report in the scorer's output.")
    return None


def _finish(job_id: str, state: str, report: dict | None = None, error: str | None = None) -> None:
    with _lock:
        if _job and _job["id"] == job_id:
            _job["state"] = state
            _job["finished_at"] = _now()
            _job["report"] = report
            _job["error"] = error
